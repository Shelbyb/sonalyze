'use client';

import { useEffect, useState } from 'react';
import { Wand2, CheckCircle2, ExternalLink, RefreshCw } from 'lucide-react';
import {
  getUserPlaylists,
  getPlaylistTracks,
  getRecommendations,
  createPlaylist,
  addTracksToPlaylist,
  getMe,
  searchTracks,
  getTopTracks,
} from '@/lib/spotify';
import type { SpotifyPlaylist, SpotifyTrack } from '@/types/spotify';
import PageHeader from '@/components/PageHeader';
import { LoadingState, ErrorState } from '@/components/StateViews';
import TrackRow from '@/components/TrackRow';
import { useSpotifyToken } from '@/hooks';

type Stage = 'pick' | 'tuning' | 'results' | 'saved';

export default function DiscoverPage() {
  const { token } = useSpotifyToken();

  const [stage, setStage] = useState<Stage>('pick');
  const [playlists, setPlaylists] = useState<SpotifyPlaylist[] | null>(null);
  const [selectedPlaylist, setSelectedPlaylist] = useState<string>('');
  const [error, setError] = useState<string | null>(null);

  const [energy, setEnergy] = useState(0.6);
  const [valence, setValence] = useState(0.6);
  const [danceability, setDanceability] = useState(0.6);

  const [loadingRecs, setLoadingRecs] = useState(false);
  const [recommendations, setRecommendations] = useState<SpotifyTrack[]>([]);
  const [selected, setSelected] = useState<Set<string>>(new Set());

  const [playlistName, setPlaylistName] = useState('');
  const [playlistDesc, setPlaylistDesc] = useState('');
  const [saving, setSaving] = useState(false);
  const [savedUrl, setSavedUrl] = useState<string | null>(null);

  useEffect(() => {
    if (!token) return;
    getUserPlaylists(token, 50)
      .then((res) => setPlaylists((res?.items || []).filter(Boolean)))
      .catch((e) => setError(e.message));
  }, [token]);

  async function generate() {
    if (!token || !selectedPlaylist) return;
    setLoadingRecs(true);
    setError(null);
    try {
      const seedPlaylist = playlists?.find((p) => p.id === selectedPlaylist);
      let playableItems: { track: SpotifyTrack }[] = [];

      try {
        const { items } = await getPlaylistTracks(token, selectedPlaylist, 40);
        playableItems = (items || []).filter((i) => Boolean(i?.track?.id));
      } catch {
        // Continue to fallbacks if direct playlist tracks are inaccessible (e.g. 403 on curated playlists)
      }

      // If playlist tracks are empty or restricted (e.g., 403 on Spotify editorial/curated playlists),
      // search Spotify catalog using the playlist's title as query
      if (playableItems.length === 0 && seedPlaylist?.name) {
        try {
          const searchRes = await searchTracks(token, seedPlaylist.name, 20);
          playableItems = (searchRes?.tracks?.items || [])
            .filter((t) => Boolean(t?.id))
            .map((t) => ({ track: t }));
        } catch {
          // Continue to next fallback
        }
      }

      // If still empty, fall back to user's top listening tracks as seed
      if (playableItems.length === 0) {
        try {
          const topRes = await getTopTracks(token, 'short_term', 20);
          playableItems = (topRes?.items || [])
            .filter((t) => Boolean(t?.id))
            .map((t) => ({ track: t }));
        } catch {
          // Ignore
        }
      }

      if (playableItems.length === 0) {
        setError('That playlist has no playable tracks to use as a seed.');
        setLoadingRecs(false);
        return;
      }

      const seedTracks = [...playableItems]
        .sort(() => Math.random() - 0.5)
        .slice(0, 5)
        .map((i) => i.track);

      const res = await getRecommendations(token, {
        seedTracks: seedTracks.map((t) => t.id),
        seedTrackObjects: seedTracks.map((t) => ({
          name: t.name,
          artist: t.artists?.[0]?.name ?? '',
        })),
        targetEnergy: energy,
        targetValence: valence,
        targetDanceability: danceability,
        limit: 20,
      });

      const recTracks = res?.tracks || [];
      if (recTracks.length === 0) {
        setError(
          'No recommendations could be found for this playlist. Try another seed playlist.',
        );
        return;
      }

      setRecommendations(recTracks);
      setSelected(new Set(recTracks.map((t) => t?.id).filter(Boolean)));

      setPlaylistName(`${seedPlaylist?.name ?? 'My mix'} — Recommended`);
      setPlaylistDesc(
        `Generated by Sonalyze from "${seedPlaylist?.name ?? 'a playlist'}".`,
      );

      setStage('results');
    } catch (e: any) {
      setError(e.message || 'Failed to generate recommendations.');
    } finally {
      setLoadingRecs(false);
    }
  }

  function toggleTrack(id: string) {
    setSelected((prev) => {
      const next = new Set(prev);
      next.has(id) ? next.delete(id) : next.add(id);
      return next;
    });
  }

  async function save() {
    if (!token) return;
    setSaving(true);
    setError(null);
    try {
      const me = await getMe(token);
      const chosen = recommendations.filter((t) => selected.has(t.id));
      const playlist = await createPlaylist(
        token,
        me.id,
        playlistName || 'My generated mix',
        playlistDesc,
        false,
      );
      await addTracksToPlaylist(
        token,
        playlist.id,
        chosen.map((t) => `spotify:track:${t.id}`),
      );
      setSavedUrl(
        playlist.external_urls?.spotify ||
          `https://open.spotify.com/playlist/${playlist.id}`,
      );
      setStage('saved');
    } catch (e: any) {
      setError(e.message);
    } finally {
      setSaving(false);
    }
  }

  function reset() {
    setStage('pick');
    setSelectedPlaylist('');
    setRecommendations([]);
    setSelected(new Set());
    setSavedUrl(null);
    setError(null);
  }

  return (
    <div>
      <PageHeader
        eyebrow="Create"
        title="Playlist generator"
        description="Pick one of your playlists as a starting point, tune the mood, and Sonalyze will suggest new tracks you can save straight to Spotify."
      />

      {error && <ErrorState message="Something went wrong." hint={error} />}

      {stage === 'pick' && (
        <div className="max-w-xl">
          {!playlists && !error && <LoadingState label="Loading your playlists" />}
          {playlists && (
            <div className="bg-panel/40 space-y-6 rounded-2xl border border-white/8 p-6">
              <div>
                <label className="text-cream mb-2 block text-sm font-medium">
                  Choose a seed playlist
                </label>
                <select
                  value={selectedPlaylist}
                  onChange={(e) => setSelectedPlaylist(e.target.value)}
                  className="bg-elevated text-cream focus:border-accent w-full rounded-lg border border-white/10 px-4 py-2.5 text-sm focus:outline-none"
                >
                  <option value="">Select a playlist…</option>
                  {playlists.map((p) => {
                    const count = p.tracks?.total;
                    const countLabel = count !== undefined ? ` (${count} tracks)` : '';
                    return (
                      <option key={p.id} value={p.id}>
                        {p.name || 'Untitled Playlist'}
                        {countLabel}
                      </option>
                    );
                  })}
                </select>
              </div>

              <button
                disabled={!selectedPlaylist}
                onClick={() => setStage('tuning')}
                className="bg-accent inline-flex items-center gap-2 rounded-full px-5 py-2.5 text-sm font-semibold text-black transition-transform hover:scale-[1.03] disabled:cursor-not-allowed disabled:opacity-40"
              >
                Next: tune the mood
              </button>
            </div>
          )}
        </div>
      )}

      {stage === 'tuning' && (
        <div className="bg-panel/40 max-w-xl space-y-6 rounded-2xl border border-white/8 p-6">
          <Slider
            label="Energy"
            value={energy}
            onChange={setEnergy}
            lowLabel="Mellow"
            highLabel="Intense"
          />
          <Slider
            label="Mood"
            value={valence}
            onChange={setValence}
            lowLabel="Moody"
            highLabel="Upbeat"
          />
          <Slider
            label="Danceability"
            value={danceability}
            onChange={setDanceability}
            lowLabel="Freeform"
            highLabel="Groove-heavy"
          />

          <div className="flex gap-3">
            <button
              onClick={() => setStage('pick')}
              className="text-muted hover:text-cream rounded-full border border-white/10 px-5 py-2.5 text-sm font-medium"
            >
              Back
            </button>
            <button
              onClick={generate}
              disabled={loadingRecs}
              className="bg-accent inline-flex items-center gap-2 rounded-full px-5 py-2.5 text-sm font-semibold text-black transition-transform hover:scale-[1.03] disabled:opacity-60"
            >
              <Wand2 className="h-4 w-4" />
              {loadingRecs ? 'Generating…' : 'Generate recommendations'}
            </button>
          </div>
        </div>
      )}

      {stage === 'results' && (
        <div className="space-y-6">
          <div className="bg-panel/40 rounded-2xl border border-white/8 p-2">
            {recommendations.map((t) => (
              <label
                key={t.id}
                className="hover:bg-elevated/40 flex cursor-pointer items-center gap-3 rounded-xl px-3 transition-colors"
              >
                <input
                  type="checkbox"
                  checked={selected.has(t.id)}
                  onChange={() => toggleTrack(t.id)}
                  className="accent-accentDeep h-4 w-4 shrink-0"
                />
                <div className="flex-1">
                  <TrackRow track={t} />
                </div>
              </label>
            ))}
          </div>

          <div className="bg-panel/40 max-w-xl space-y-4 rounded-2xl border border-white/8 p-6">
            <div>
              <label className="text-cream mb-2 block text-sm font-medium">
                Playlist name
              </label>
              <input
                value={playlistName}
                onChange={(e) => setPlaylistName(e.target.value)}
                className="bg-elevated text-cream focus:border-accent w-full rounded-lg border border-white/10 px-4 py-2.5 text-sm focus:outline-none"
              />
            </div>
            <div>
              <label className="text-cream mb-2 block text-sm font-medium">
                Description
              </label>
              <input
                value={playlistDesc}
                onChange={(e) => setPlaylistDesc(e.target.value)}
                className="bg-elevated text-cream focus:border-accent w-full rounded-lg border border-white/10 px-4 py-2.5 text-sm focus:outline-none"
              />
            </div>
            <div className="flex gap-3">
              <button
                onClick={() => setStage('tuning')}
                className="text-muted hover:text-cream inline-flex items-center gap-2 rounded-full border border-white/10 px-5 py-2.5 text-sm font-medium"
              >
                <RefreshCw className="h-4 w-4" /> Adjust mood
              </button>
              <button
                onClick={save}
                disabled={saving || selected.size === 0}
                className="bg-accent inline-flex items-center gap-2 rounded-full px-5 py-2.5 text-sm font-semibold text-black transition-transform hover:scale-[1.03] disabled:opacity-60"
              >
                {saving ? 'Saving…' : `Save ${selected.size} tracks to Spotify`}
              </button>
            </div>
          </div>
        </div>
      )}

      {stage === 'saved' && savedUrl && (
        <div className="border-accent/30 bg-accent/5 flex max-w-xl flex-col items-center gap-4 rounded-2xl border p-10 text-center">
          <CheckCircle2 className="text-accent h-10 w-10" />
          <h2 className="font-display text-xl font-semibold tracking-tight">
            Playlist saved
          </h2>
          <p className="text-muted text-sm">
            "{playlistName}" is now in your Spotify library.
          </p>
          <div className="flex gap-3">
            <a
              href={savedUrl}
              target="_blank"
              rel="noreferrer"
              className="bg-accent inline-flex items-center gap-2 rounded-full px-5 py-2.5 text-sm font-semibold text-black transition-transform hover:scale-[1.03]"
            >
              Open in Spotify <ExternalLink className="h-4 w-4" />
            </a>
            <button
              onClick={reset}
              className="text-muted hover:text-cream rounded-full border border-white/10 px-5 py-2.5 text-sm font-medium"
            >
              Make another
            </button>
          </div>
        </div>
      )}
    </div>
  );
}

function Slider({
  label,
  value,
  onChange,
  lowLabel,
  highLabel,
}: {
  label: string;
  value: number;
  onChange: (v: number) => void;
  lowLabel: string;
  highLabel: string;
}) {
  return (
    <div>
      <div className="mb-2 flex items-baseline justify-between">
        <span className="text-cream text-sm font-medium">{label}</span>
        <span className="text-subtle text-xs">{Math.round(value * 100)}%</span>
      </div>
      <input
        type="range"
        min={0}
        max={1}
        step={0.05}
        value={value}
        onChange={(e) => onChange(parseFloat(e.target.value))}
        className="accent-accentDeep w-full"
      />
      <div className="text-subtle mt-1 flex justify-between text-[11px]">
        <span>{lowLabel}</span>
        <span>{highLabel}</span>
      </div>
    </div>
  );
}
